/* Exact seven-slot optimizer, mirrored from fourth_down/optimizer.py.
   Forecasts are generated by Python; this browser engine only assigns slots. */
"use strict";
const FourthDownEngine = (() => {
  const slots = ["QB", "RB1", "RB2", "WR1", "WR2", "TE", "FLEX"];
  const eligible = [
    ["QB"],
    ["RB"],
    ["RB"],
    ["WR"],
    ["WR"],
    ["TE"],
    ["RB", "WR", "TE"],
  ];
  function optimize(players, steady = false) {
    const ordered = [...players].sort((a, b) => a.id.localeCompare(b.id));
    if (new Set(ordered.map((p) => p.id)).size !== ordered.length)
      throw Error("Duplicate player");
    let dp = new Map([[0, { score: 0, picks: [] }]]);
    ordered.forEach((p) => {
      const previous = new Map(dp);
      previous.forEach(({ score, picks }, mask) => {
        slots.forEach((slot, i) => {
          if (mask & (1 << i) || !eligible[i].includes(p.position)) return;
          const next = mask | (1 << i),
            value = score + p.projection - (steady ? 0.25 * p.volatility : 0);
          if (!dp.has(next) || value > dp.get(next).score + 1e-10)
            dp.set(next, {
              score: value,
              picks: [...picks, { ...p, slot, slotIndex: i }],
            });
        });
      });
    });
    const result = dp.get(127);
    return result
      ? {
          feasible: true,
          lineup: result.picks.sort((a, b) => a.slotIndex - b.slotIndex),
          objective: result.score,
          projection: result.picks.reduce((sum, p) => sum + p.projection, 0),
        }
      : { feasible: false, lineup: [], projection: null, objective: null };
  }
  return { optimize, slots };
})();
if (typeof module !== "undefined") module.exports = FourthDownEngine;
