"""Build the season presentation from the preserved case and roster sources."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEAMS = {
    "ARI": "Arizona Cardinals", "ATL": "Atlanta Falcons", "BAL": "Baltimore Ravens",
    "BUF": "Buffalo Bills", "CAR": "Carolina Panthers", "CHI": "Chicago Bears",
    "CIN": "Cincinnati Bengals", "CLE": "Cleveland Browns", "DAL": "Dallas Cowboys",
    "DEN": "Denver Broncos", "DET": "Detroit Lions", "GB": "Green Bay Packers",
    "HOU": "Houston Texans", "IND": "Indianapolis Colts", "JAX": "Jacksonville Jaguars",
    "KC": "Kansas City Chiefs", "LAR": "Los Angeles Rams", "LAC": "Los Angeles Chargers",
    "LV": "Las Vegas Raiders", "MIA": "Miami Dolphins", "MIN": "Minnesota Vikings",
    "NE": "New England Patriots", "NO": "New Orleans Saints", "NYG": "New York Giants",
    "NYJ": "New York Jets", "PHI": "Philadelphia Eagles", "PIT": "Pittsburgh Steelers",
    "SEA": "Seattle Seahawks", "SF": "San Francisco 49ers", "TB": "Tampa Bay Buccaneers",
    "TEN": "Tennessee Titans", "WAS": "Washington Commanders",
}


def build():
    read = lambda path: json.loads((ROOT / path).read_text(encoding="utf-8"))
    repo = "https://github.com/Adam-Skarre/fourth-down-/blob/main/"
    payload = {
        "firstSeason": read("data/seasons/2024_draft.json"),
        "championship": {
            "roster": read("data/championship_2025/roster.json"),
            "report": read("reports/championship_2025.json"),
        },
        "current": read("data/seasons/2026_week7.json"),
        "teams": TEAMS,
        "sources": {
            "roster": repo + "data/championship_2025/roster.json",
            "report": repo + "reports/championship_2025.json",
            "method": repo + "docs/CHAMPIONSHIP_2025.md",
            "current": repo + "data/seasons/2026_week7.json",
            "firstSeason": repo + "data/seasons/2024_draft.json",
        },
    }
    target = ROOT / "site/seasons-data.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    content = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    target.write_text(
        "/* Generated by python -m scripts.build_seasons; do not edit. */\n"
        "window.FOURTH_DOWN_SEASONS = " + content.replace("<", "\\u003c") + ";\n",
        encoding="utf-8",
    )
    print("Built season presentation: 2024 first season, 2025 retrospective and 2026 testing roster.")


if __name__ == "__main__":
    build()
